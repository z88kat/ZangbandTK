def read_prf():
    """The generated file, back in, as the game reads it."""
    out = {k: {} for k in ('monster', 'feat', 'flavor', 'trap', 'GF', 'object')}
    path = os.path.join(OUT, 'graf-neo.prf')
    for line in open(path, encoding='utf-8'):
        m = re.match(r'(monster|feat|flavor|trap|GF|object):(.+)'
                     r':0x([0-9A-F]{2}):0x([0-9A-F]{2})$', line.strip())
        if not m:
            continue
        kind, key, a, c = m.groups()
        cell = (int(a, 16) & 0x7f, int(c, 16) & 0x7f)
        if kind == 'flavor':
            out[kind][int(key)] = cell
        elif kind in ('feat', 'trap', 'GF', 'object'):
            head, tail = key.rsplit(':', 1)
            out[kind][(head, tail)] = cell
        else:
            out[kind][key] = cell
    return out


def make_preview(sheet, zoom=3, filename='preview.png'):
    prf = read_prf()
    first = {}
    for index, _, tval in read_flavours():
        first.setdefault(tval, index)
    map_flavour = {ch: first[tval] for ch, tval in MAP_OBJ_TVAL.items()
                   if tval in first}
    px = read_png(os.path.join(OUT, '16x16.png'))
    missing = []
    widths = {len(row) for row in MAP}
    assert len(widths) == 1, 'the preview map is ragged: %s' % widths

    rows = len(MAP) + 1 + len(FAMILIES)
    cols = max(len(MAP[0]), max(len(f) for f in FAMILIES))
    W, H = cols * TILE * zoom, rows * TILE * zoom
    out = [[(0, 0, 0, 255)] * W for _ in range(H)]

    def blit(cell, tx, ty):
        if cell is None:
            return
        r, c = cell
        for y in range(TILE):
            for x in range(TILE):
                p = px[r * TILE + y][c * TILE + x]
                if p[:3] == (0, 0, 0):
                    continue
                for dy in range(zoom):
                    for dx in range(zoom):
                        out[(ty * TILE + y) * zoom + dy][(tx * TILE + x) * zoom + dx] = p

    def find(table, key):
        if key not in table:
            missing.append(key)
            return None
        return table[key]

    for ty, line in enumerate(MAP):
        for tx, ch in enumerate(line):
            if ch in MAP_FEAT:
                blit(find(prf['feat'], (MAP_FEAT[ch], 'lit')), tx, ty)
                continue
            # Everything else stands on something: town fittings on grass,
            # dungeon contents on floor.
            under = 'GRASS' if tx < 14 else 'FLOOR'
            blit(find(prf['feat'], (under, 'lit')), tx, ty)
            if ch in MAP_MON:
                blit(find(prf['monster'], MAP_MON[ch]), tx, ty)
            elif ch in MAP_TRAP:
                blit(find(prf['trap'], (MAP_TRAP[ch], 'lit')), tx, ty)
            elif ch in MAP_GF:
                blit(find(prf['GF'], MAP_GF[ch]), tx, ty)
            elif ch in MAP_OBJ:
                blit(find(prf['object'], MAP_OBJ[ch]), tx, ty)
            elif ch in map_flavour:
                blit(find(prf['flavor'], map_flavour[ch]), tx, ty)

    for i, family in enumerate(FAMILIES):
        for tx, name in enumerate(family):
            blit(find(prf['monster'], name), tx, len(MAP) + 1 + i)

    path = os.path.join(SRC, filename)
    write_png(path, out)
    print('\n  preview: %s (%dx%d)' % (path, W, H))
    if missing:
        print('  MISSING from the prf: %s' % sorted(set(map(str, missing)))[:6])


