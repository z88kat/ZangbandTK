/**
 * \file list-kinds-v1.h
 * \brief The object kinds as version 1 of the "object memory" block numbered them
 *
 * Version 1 of that block recorded what the character knows of each object
 * kind -- seen, tried, aware, ignored -- by the kind's position in k_info, and
 * nothing else.  A position means something only against the list it was
 * counted in, and that list moves whenever a kind is added: the kinds after it
 * shift up by one, and every savefile's knowledge with them.  The magical
 * figurine was the first kind added after version 2 started writing kinds by
 * name, and this is the list as it stood just before it arrived (3.73.0 to
 * 3.128.x), taken from the game's own k_info rather than worked out from the
 * data files.
 *
 * So the version 1 reader looks a position up here, and then looks the name
 * up in the game as it is now.  Nothing need be done to this file when a kind
 * is added, moved or renamed later: a rename is answered by rename.txt, as it
 * is for an object in the pack, and a kind that has gone takes its knowledge
 * with it (game/saves asks for that to be written down in rename.txt too).
 * It is frozen, and editing it changes what old savefiles mean.
 *
 * Savefiles older than 3.73.0 counted against shorter lists, and are read
 * against this one as they always have been -- see rd_object_memory_1().
 *
 * One entry per position: the object base's name and the kind's name as
 * obj_desc_name_format() writes it.  Position 463 is the empty kind that
 * finish_parse_object() leaves between the object files and the class books.
 */

